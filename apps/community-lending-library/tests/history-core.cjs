'use strict';
const assert=require('node:assert/strict'),path=require('node:path');
const {createHash}=require('node:crypto'),fs=require('node:fs');
const app='community-lending-library';
const root=process.env.PALE_RUNTIME_ROOT||path.resolve(__dirname,'../../../runtime');
const {prepare}=require(path.join(root,'prepare.cjs')),{Client}=require(path.join(root,'client.cjs'));
const src=path.resolve(__dirname,'..'), staging=prepare(src), history=require('../data/evaluation-v1.json');
const provenance=require('../data/dataset-v1.json'), report=require('../data/coverage-v1.json');
const base=require('../fixtures/minimal.json'), binding=require('../fixtures/binding.json');
const state=path.join(staging.root,'history-test'), run='lending-evaluation-proof';
const make=(role,id=run)=>new Client(app,role,id,state,'history-'+role,{registry:staging.registry,...(role==='infra'?{initialProfile:'sandbox'}:{})});
const i=make('infra'),a=make('agent'),isolated=make('agent','lending-unrelated'),otherI=make('infra','lending-unrelated');
const ok=(r,status='ok')=>{assert.equal(r.status,status,JSON.stringify(r));return r;};
const read=n=>a.call(app+'.'+n,{});
async function main(){
 assert.equal(createHash('sha256').update(fs.readFileSync(path.join(src,'data','evaluation-v1.json'))).digest('hex'),report.sha256);
 await Promise.all([i.initialize(),a.initialize(),isolated.initialize(),otherI.initialize()]);
 ok(await otherI.call('env.snapshot'));
 const initial=ok(await i.call('env.snapshot'));
 const bundle={...initial.snapshot.resources.bundle,dataset:provenance};
 const opts={expected_version:initial.version,bundle,binding,data:history,virtual_now:history.materialized_at,request_id:'load-history-exact'};
 const beforeFloor={...history,seed_at:'2024-12-31T23:59:59+08:00'};
 ok(await i.call('env.load_seed',{...opts,data:beforeFloor,request_id:'reject-pre-floor'}),'invalid_seed');
 const loaded=ok(await i.call('env.load_seed',opts),'ready');
 const snapshots=ok(await i.call('env.snapshot'));
 assert.deepEqual(snapshots.snapshot.data,history);
 assert.equal(snapshots.snapshot.resources.quality.automated_pass,true);
 assert.equal(snapshots.snapshot.data.queue_history.length,72);
 const reportDates=r=>new Set(r.map(x=>x.slice(0,4)));
 const own=h=>h.member_id===history.member_id;
 const holds=ok(await read('list_holds')).holds,loans=ok(await read('list_loans')).loans,receipts=ok(await read('list_activity')).attempts;
 assert.deepEqual(holds.map(r=>r.id),history.holds.filter(own).map(r=>r.id));
 assert.deepEqual(loans.map(r=>r.id),history.loans.filter(own).map(r=>r.id));
 assert.deepEqual(receipts.map(r=>r.id),history.attempts.filter(own).map(r=>r.id));
 assert.deepEqual(reportDates(holds.map(x=>x.created_at)),new Set(['2025','2026']));
 assert.deepEqual(reportDates(loans.map(x=>x.checked_out_at)),new Set(['2025','2026']));
 assert.equal(holds.length+loans.length+receipts.length>80,true);
 assert.ok(loans.some(x=>x.renewed&&x.returned_at));
 assert.ok(receipts.some(x=>x.status==='accepted'));
 assert.ok(receipts.some(x=>x.status==='rejected'));
 assert.equal(ok(await isolated.call(app+'.list_holds',{})).holds[0].id,base.holds[0].id);
 const changed=ok(await a.call(app+'.confirm_hold',{item_id:'I1',copy_id:'C1',expected_version:loaded.version,request_id:'local-change'}),'committed');
 assert.equal(ok(await read('list_holds')).holds.length,holds.length+1);
 const reset=ok(await i.call('env.reset',{expected_version:changed.version}),'ready');
 assert.ok(reset.version.epoch>changed.version.epoch);
 assert.deepEqual(ok(await i.call('env.snapshot')).snapshot.data,history);
 assert.deepEqual(ok(await i.call('env.snapshot')).snapshot.receipts,{});
 assert.deepEqual(ok(await read('list_holds')).holds,holds);
 console.log('PASS: versioned full-window seed in real Infra MCP; 2025 accepted, pre-floor rejected; separate Agent queried '+holds.length+' holds, '+loans.length+' loans and '+receipts.length+' attempts; owner scope, other-run isolation and reset verified.');
}
main().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{await Promise.allSettled([i.close(),a.close(),isolated.close(),otherI.close()]);staging.cleanup();});
